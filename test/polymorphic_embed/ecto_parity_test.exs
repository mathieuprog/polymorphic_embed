# Mirrors test/ecto/changeset/embedded_test.exs from Ecto v3.12.1.
#
# The goal is output parity: for the same input, a polymorphic embed gives
# the same output as an Ecto embed. Each test keeps the name and the
# assertions of the Ecto test. The only changes are the ones a polymorphic
# field needs: a type key in the params, cast_polymorphic_embed/3 in place of
# cast_embed/3, `with:` as a keyword list of types, and
# PolymorphicEmbed.traverse_errors/2. Tests for Ecto features that
# polymorphic embeds do not have are left out.
#
# A polymorphic embed keeps a valid child as a struct in the changes, and an
# Ecto embed keeps a changeset. Tests that read the changes, the action or
# the validity of a valid child, and tests that expect :replace changesets,
# are therefore left out too.
defmodule PolymorphicEmbed.EctoParityTest do
  use ExUnit.Case, async: true

  alias Ecto.Changeset

  alias __MODULE__.{Author, AutoIdPost, Post, Profile}

  defmodule Post do
    use Ecto.Schema
    import Ecto.Changeset

    # Ecto uses `schema "posts"`. Polymorphic embeds generate ids at cast time
    # and crash on an autogenerated integer id, see the test for AutoIdPost.
    @primary_key {:id, :id, autogenerate: false}
    schema "posts" do
      field :title, :string
      field :position, :integer
    end

    def changeset(schema, params) do
      cast(schema, params, ~w(title)a)
      |> validate_required(:title)
      |> validate_length(:title, min: 3)
    end

    def optional_changeset(schema, params) do
      cast(schema, params, ~w(title)a)
    end
  end

  defmodule Profile do
    use Ecto.Schema
    import Ecto.Changeset

    embedded_schema do
      field :name
    end

    def changeset(schema, params) do
      cast(schema, params, ~w(name id)a)
      |> validate_required(:name)
      |> validate_length(:name, min: 3)
    end

    def optional_changeset(schema, params) do
      cast(schema, params, ~w(name)a)
    end
  end

  defmodule AutoIdPost do
    use Ecto.Schema

    schema "posts" do
      field :title, :string
    end

    def changeset(schema, params), do: Ecto.Changeset.cast(schema, params, [:title])
  end

  defmodule Author do
    use Ecto.Schema
    import PolymorphicEmbed

    # Polymorphic embeds only accept on_replace: :update for one and
    # on_replace: :delete for many.
    schema "authors" do
      field :name, :string
      polymorphic_embeds_one :profile, types: [profile: Profile], on_replace: :update
      polymorphic_embeds_many :posts, types: [post: Post], on_replace: :delete
      polymorphic_embeds_many :auto_id_posts, types: [post: AutoIdPost], on_replace: :delete
    end
  end

  defp cast(schema, params, embed, opts \\ []) do
    schema
    |> Changeset.cast(params, ~w())
    |> PolymorphicEmbed.cast_polymorphic_embed(embed, opts)
  end

  defp profile(params), do: Map.put(params, "__type__", "profile")
  defp post(params), do: Map.put(params, "__type__", "post")

  ## Cast embeds one

  test "cast embeds_one with invalid params" do
    changeset = cast(%Author{}, %{"profile" => profile(%{})}, :profile)
    assert changeset.changes.profile.changes == %{}
    assert changeset.changes.profile.errors == [name: {"can't be blank", [validation: :required]}]
    assert changeset.changes.profile.action == :insert
    refute changeset.changes.profile.valid?
    refute changeset.valid?
  end

  test "cast embeds_one with invalid params: string" do
    changeset = cast(%Author{}, %{"profile" => "value"}, :profile, required: true)
    assert changeset.errors == [profile: {"is invalid", [validation: :embed, type: :map]}]
    refute changeset.valid?
  end

  test "cast embeds_one with invalid params: list" do
    changeset = cast(%Author{}, %{"profile" => [profile(%{"name" => "michal"})]}, :profile)
    assert changeset.changes == %{}
    assert changeset.errors == [profile: {"is invalid", [validation: :embed, type: :map]}]
  end

  test "cast embeds_one without changes skips" do
    changeset =
      cast(
        %Author{profile: %Profile{name: "michal", id: "michal"}},
        %{"profile" => profile(%{"id" => "michal"})},
        :profile
      )

    assert changeset.changes == %{}
    assert changeset.errors == []
  end

  test "cast embeds_one when required" do
    changeset = cast(%Author{profile: nil}, %{}, :profile, required: true)
    assert changeset.required == [:profile]
    assert changeset.changes == %{}
    assert changeset.errors == [profile: {"can't be blank", [validation: :required]}]
  end

  test "cast embeds_one when required with nil params" do
    changeset = cast(%Author{profile: nil}, %{"profile" => nil}, :profile, required: true)
    assert changeset.required == [:profile]
    assert changeset.changes == %{}
    assert changeset.errors == [profile: {"can't be blank", [validation: :required]}]
  end

  test "cast embeds_one when required with nil params and existing data" do
    changeset = cast(%Author{profile: %Profile{}}, %{"profile" => nil}, :profile, required: true)
    assert changeset.required == [:profile]
    assert changeset.changes == %{profile: nil}
    assert changeset.errors == [profile: {"can't be blank", [validation: :required]}]
  end

  test "cast embeds_one with optional" do
    changeset = cast(%Author{profile: %Profile{id: "id"}}, %{"profile" => nil}, :profile)
    assert changeset.changes.profile == nil
    assert changeset.valid?
  end

  test "raises when :update is used on embeds_many" do
    assert_raise ArgumentError, fn ->
      defmodule Topic do
        use Ecto.Schema
        import PolymorphicEmbed

        schema "topics" do
          polymorphic_embeds_many :tags, types: [post: Post], on_replace: :update
        end
      end
    end
  end

  # Not in Ecto: Ecto casts this schema without an error.
  test "cast embeds_many with an autogenerated integer id" do
    changeset =
      cast(%Author{}, %{"auto_id_posts" => [post(%{"title" => "hello"})]}, :auto_id_posts)

    assert changeset.valid?

    assert [%AutoIdPost{id: nil, title: "hello"}] =
             Changeset.apply_changes(changeset).auto_id_posts
  end

  ## cast embeds many

  describe "cast embeds_many with map and sort_param and delete_param" do
    setup do
      posts = %{
        1 => post(%{"title" => "one"}),
        2 => post(%{"title" => "two"}),
        3 => post(%{"title" => "three"})
      }

      %{posts: posts, opts: [sort_param: :sort, drop_param: :drop]}
    end

    test "sort creates a new entry", %{opts: opts} do
      changeset = cast(%Author{}, %{sort: ["new"]}, :posts, opts)
      assert Enum.map(changeset.changes.posts, & &1.changes[:title]) == [nil]
    end
  end

  test "cast embeds_many with invalid params: string" do
    changeset = cast(%Author{}, %{"posts" => "value"}, :posts)
    assert changeset.errors == [posts: {"is invalid", [validation: :embed, type: {:array, :map}]}]
    refute changeset.valid?
  end

  test "cast embeds_many with invalid params: list of strings" do
    changeset = cast(%Author{}, %{"posts" => ["value"]}, :posts)
    assert changeset.errors == [posts: {"is invalid", [validation: :embed, type: {:array, :map}]}]
    refute changeset.valid?
  end

  test "cast embeds_many with invalid params: nil" do
    changeset = cast(%Author{}, %{"posts" => nil}, :posts)
    assert changeset.errors == [posts: {"is invalid", [validation: :embed, type: {:array, :map}]}]
    refute changeset.valid?
  end

  test "cast embeds_many with invalid params: map that is not indexed" do
    changeset = cast(%Author{}, %{"posts" => %{"id" => "invalid"}}, :posts)
    assert changeset.errors == [posts: {"is invalid", [validation: :embed, type: {:array, :map}]}]
    refute changeset.valid?
  end

  test "cast embeds_many without changes skips" do
    changeset =
      cast(
        %Author{posts: [%Post{title: "hello", id: 1}]},
        %{"posts" => [post(%{"id" => 1})]},
        :posts
      )

    refute Map.has_key?(changeset.changes, :posts)
  end

  test "cast embeds_many when required" do
    changeset = cast(%Author{posts: []}, %{}, :posts, required: true)
    assert changeset.required == [:posts]
    assert changeset.changes == %{}
    assert changeset.errors == [posts: {"can't be blank", [validation: :required]}]
  end

  test "cast embeds_many when required with nil params" do
    changeset = cast(%Author{posts: []}, %{"posts" => nil}, :posts, required: true)
    assert changeset.changes == %{}
    assert changeset.errors == [posts: {"is invalid", [validation: :embed, type: {:array, :map}]}]
  end

  test "cast embeds_many with empty parameters" do
    changeset = cast(%Author{posts: []}, %{}, :posts)
    assert changeset.changes == %{}

    changeset = cast(%Author{posts: [%Post{}]}, %{}, :posts)
    assert changeset.changes == %{}
  end

  ## traverse_errors

  defp upcase_errors(changeset) do
    PolymorphicEmbed.traverse_errors(changeset, fn {msg, opts} ->
      msg
      |> String.replace("%{count}", to_string(opts[:count]))
      |> String.upcase()
    end)
  end

  test "traverses changeset errors with embeds_one error" do
    params = %{"name" => "hi", "profile" => profile(%{"name" => "hi"})}

    changeset =
      %Author{}
      |> Changeset.cast(params, ~w(name)a)
      |> PolymorphicEmbed.cast_polymorphic_embed(:profile)
      |> Changeset.add_error(:name, "is invalid")

    assert upcase_errors(changeset) == %{
             profile: %{name: ["SHOULD BE AT LEAST 3 CHARACTER(S)"]},
             name: ["IS INVALID"]
           }
  end

  test "traverses changeset errors with embeds_many errors" do
    params = %{
      "name" => "hi",
      "posts" => [post(%{"title" => "hi"}), post(%{"title" => "valid"})]
    }

    changeset =
      %Author{}
      |> Changeset.cast(params, ~w(name)a)
      |> PolymorphicEmbed.cast_polymorphic_embed(:posts)
      |> Changeset.add_error(:name, "is invalid")

    assert upcase_errors(changeset) == %{
             posts: [%{title: ["SHOULD BE AT LEAST 3 CHARACTER(S)"]}, %{}],
             name: ["IS INVALID"]
           }
  end

  test "traverses changeset errors with embeds_many when required" do
    changeset = cast(%Author{posts: []}, %{}, :posts, required: true)
    assert changeset.errors == [posts: {"can't be blank", [validation: :required]}]

    assert PolymorphicEmbed.traverse_errors(changeset, & &1) == %{
             posts: [{"can't be blank", [validation: :required]}]
           }

    changeset = cast(%Author{}, %{"posts" => []}, :posts, required: true)
    assert changeset.errors == [posts: {"can't be blank", [validation: :required]}]

    assert PolymorphicEmbed.traverse_errors(changeset, & &1) == %{
             posts: [{"can't be blank", [validation: :required]}]
           }

    changeset = cast(%Author{posts: []}, %{"posts" => nil}, :posts, required: true)
    assert changeset.errors == [posts: {"is invalid", [validation: :embed, type: {:array, :map}]}]

    assert PolymorphicEmbed.traverse_errors(changeset, & &1) == %{
             posts: [{"is invalid", [validation: :embed, type: {:array, :map}]}]
           }

    changeset =
      cast(%Author{posts: []}, %{"posts" => [%{title: nil, __type__: "post"}]}, :posts,
        required: true
      )

    assert changeset.errors == []

    assert PolymorphicEmbed.traverse_errors(changeset, & &1) == %{
             posts: [%{title: [{"can't be blank", [validation: :required]}]}]
           }
  end
end
